"""Phase T WP3 M1 Dynamic Reference Budget Policy.

Trains and evaluates M1 models that select the reference budget
``k \\in {1, 3, 6}`` per query based on test-time-safe features. Episode
data is generated by ``run_phaseT_wp3_trainval_benchmark.py`` and stored as
``phase2_episode_instability.csv`` (per-episode k=1 statistics) and
``per_query_per_subset_metrics.csv`` (per-query per-subset Dice at each k)
in the train / val report directories.

Pipeline::

    1. Load train / val episode data + per_query_per_subset_metrics.
    2. Merge to get per-episode Dice at k=1/3/6 and 4 features.
    3. Train M1-0 .. M1-5 (baselines + handcrafted threshold + classifiers).
    4. Select (lambda_c, lambda_r) via 5-fold inner CV on train for M1-3/4/5.
    5. Evaluate each model on val (mean Dice, avg k, CVaR_0.1, CFR, cost).
    6. Select best adaptive model (highest val mean U at fixed eval lambdas).
    7. Evaluate M1 gate conditions (section 9.6) -- cost-saving OR quality-cost.
    8. Write outputs (CSVs, JSON, MD, pickle).

Models (section 9.4)::

    M1-0  Always k=1                 (baseline)
    M1-1  Always k=3                 (baseline)
    M1-2  Always k=6                 (baseline)
    M1-3  Handcrafted threshold       (disagreement > thr -> k=6, else k=1)
    M1-4  Logistic regression         (predict best k from 4 features)
    M1-5  Gradient boosting           (predict best k from 4 features)

Features (4 test-time-safe, section 9.3)::

    matching_map_disagreement
    candidate_jaccard_mean_k1
    prompt_overlap_mean_k1
    prediction_jaccard_k1_within

Training objective (section 9.5)::

    U(q, k) = Dice(q, k) - lambda_c * C(k) - lambda_r * Risk(q)
    C(k) = k / 6          (normalized matching cost)
    Risk(q) = best_worst_gap_k1   (instability-risk surrogate)

CLI::

    python src/adapromptset/scripts/run_phaseT_wp3_m1_dynamic_budget.py \\
        --train-dir reports/phaseT_wp3_train \\
        --val-dir reports/phaseT_wp3_validation \\
        --out-dir reports/phaseT_wp3_m1 \\
        --smoke
"""

