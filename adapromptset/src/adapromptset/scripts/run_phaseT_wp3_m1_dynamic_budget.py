    bundle: dict[str, Any] = {
        "model_name": best_model.name,
        "model_type": best_model.model_type,
        "feature_cols": list(FEATURE_COLS),
        "lambda_c": best_model.lambda_c,
        "lambda_r": best_model.lambda_r,
        "k_values": list(K_VALUES),
    }
    if isinstance(best_model, M1Baseline):
        bundle["fixed_k"] = best_model.fixed_k
        bundle["threshold"] = None
        bundle["scaler"] = None
        bundle["estimator"] = None
    elif isinstance(best_model, M1Threshold):
        bundle["threshold"] = best_model.threshold
        bundle["fixed_k"] = None
        bundle["scaler"] = None
        bundle["estimator"] = None
    elif isinstance(best_model, M1Sklearn):
        bundle["scaler"] = best_model.scaler
        bundle["estimator"] = best_model.estimator
        bundle["threshold"] = None
        bundle["fixed_k"] = None
    with (out_dir / "m1_model.pkl").open("wb") as fh:
        pickle.dump(bundle, fh)


