EPISODE_FLOAT_COLS = (
    "matching_map_disagreement",
    "candidate_jaccard_mean_k1",
    "prompt_overlap_mean_k1",
    "prediction_jaccard_k1_within",
    "mean_dice_k1",
    "std_dice_k1",
    "min_dice_k1",
    "max_dice_k1",
    "best_worst_gap_k1",
    "catastrophic_failure_rate_k1",
)


def load_episodes(path: Path) -> list[dict[str, Any]]:
    """Load episode rows from ``phase2_episode_instability.csv``."""
    raw = _read_csv(path)
    rows: list[dict[str, Any]] = []
    for r in raw:
        row: dict[str, Any] = {
            "query_case_id": r["query_case_id"],
            "seed": int(r["seed"]),
            "config_name": r["config_name"],
        }
        for key in EPISODE_FLOAT_COLS:
            row[key] = _row_float(r, key)
        row["n_references_k1"] = int(r.get("n_references_k1", "0") or 0)
        rows.append(row)
    return rows


def load_per_query_lookup(
    path: Path,
) -> dict[tuple[str, int, str, int], list[tuple[str, float]]]:
    """Build a lookup from ``(query, seed, config, k)`` to ``[(subset_id, dice), ...]``."""
    raw = _read_csv(path)
    lookup: dict[tuple[str, int, str, int], list[tuple[str, float]]] = {}
    for r in raw:
        key = (
            r["query_case_id"],
            int(r["seed"]),
            r["config_name"],
            int(r["k"]),
        )
        sid = r.get("subset_id", "")
        sd = _row_float(r, "subset_dice")
        lookup.setdefault(key, []).append((sid, sd))
    return lookup


def _pick_consensus(entries: list[tuple[str, float]]) -> float | None:
    """Pick the consensus Dice for a (query, seed, config, k) group.

    The directive states k=3 / k=6 use ``subset_id == 0``. The WP1 pipeline
    emits ``subset_id`` of ``"first3"`` / ``"all6"`` for those rows, so this
    helper prefers ``subset_id == "0"`` and otherwise falls back to the single
    available row (there is exactly one per (query, seed, config, k) for
    k in {3, 6}).
    """
    if not entries:
        return None
    for sid, sd in entries:
        if str(sid) == "0":
            return sd
    return entries[0][1]


def merge_k_dice(
    episodes: list[dict[str, Any]],
    pq_lookup: dict[tuple[str, int, str, int], list[tuple[str, float]]],
) -> tuple[list[dict[str, Any]], int]:
    """Add ``dice_k1`` / ``dice_k3`` / ``dice_k6`` to each episode in place.

    Returns the episodes and a count of episodes where k=3 or k=6 was missing
    (filled with the k=1 mean Dice as a conservative fallback).
    """
    n_missing = 0
    for ep in episodes:
        ep["dice_k1"] = ep["mean_dice_k1"]
        key3 = (ep["query_case_id"], ep["seed"], ep["config_name"], 3)
        key6 = (ep["query_case_id"], ep["seed"], ep["config_name"], 6)
        dice_k3 = _pick_consensus(pq_lookup.get(key3, []))
        dice_k6 = _pick_consensus(pq_lookup.get(key6, []))
        if dice_k3 is None or dice_k6 is None:
            n_missing += 1
        # Conservative fallback: k=1 mean Dice when consensus unavailable.
        ep["dice_k3"] = float(dice_k3) if dice_k3 is not None else ep["dice_k1"]
        ep["dice_k6"] = float(dice_k6) if dice_k6 is not None else ep["dice_k1"]
    return episodes, n_missing


def episodes_to_matrix(rows: list[dict[str, Any]]) -> np.ndarray:
    """Extract the 4 test-time-safe features into an (N, 4) float64 array."""
    return np.asarray(
        [[r[col] for col in FEATURE_COLS] for r in rows], dtype=np.float64
    )


# ---------------------------------------------------------------------------
# Utility / objective computation (section 9.5)
# ---------------------------------------------------------------------------

def compute_utility(
    dice_k: np.ndarray,
    sel_k: np.ndarray,
    risk: np.ndarray,
    lambda_c: float,
    lambda_r: float,
) -> np.ndarray:
    """U(q, k) = Dice(q, k) - lambda_c * C(k) - lambda_r * Risk(q)."""
    return dice_k - lambda_c * (sel_k / 6.0) - lambda_r * risk


def _select_dice(
    sel_k: np.ndarray,
    dice_k1: np.ndarray,
    dice_k3: np.ndarray,
    dice_k6: np.ndarray,
) -> np.ndarray:
    """Look up per-episode Dice for the selected k."""
    out = np.where(sel_k == 1, dice_k1, np.where(sel_k == 3, dice_k3, dice_k6))
    return out.astype(np.float64, copy=False)


def compute_best_k(
    dice_k1: np.ndarray,
    dice_k3: np.ndarray,
    dice_k6: np.ndarray,
    risk: np.ndarray,
    lambda_c: float,
    lambda_r: float,
) -> np.ndarray:
    """argmax_{k in {1,3,6}} U(q, k) for each episode."""
    u1 = compute_utility(dice_k1, np.full(len(dice_k1), 1), risk, lambda_c, lambda_r)
    u3 = compute_utility(dice_k3, np.full(len(dice_k3), 3), risk, lambda_c, lambda_r)
    u6 = compute_utility(dice_k6, np.full(len(dice_k6), 6), risk, lambda_c, lambda_r)
    stacked = np.stack([u1, u3, u6], axis=-1)  # (N, 3)
    idx = np.argmax(stacked, axis=-1)
    return np.asarray([K_VALUES[i] for i in idx], dtype=np.int64)


# ---------------------------------------------------------------------------
# M1 models
# ---------------------------------------------------------------------------

class M1Model:
    """Base class for M1 dynamic-budget models."""

    name: str
    model_type: str
    lambda_c: float
    lambda_r: float

    def fit(
        self,
        X: np.ndarray,
        dice_k1: np.ndarray,
        dice_k3: np.ndarray,
        dice_k6: np.ndarray,
        risk: np.ndarray,
    ) -> None:
        raise NotImplementedError

    def predict_k(self, X: np.ndarray) -> np.ndarray:
        """Return per-episode selected k in {1, 3, 6}."""
        raise NotImplementedError


class M1Baseline(M1Model):
    """Always select a fixed k (M1-0 / M1-1 / M1-2)."""

    def __init__(self, name: str, fixed_k: int):
        self.name = name
        self.model_type = "baseline"
        self.fixed_k = fixed_k
        self.lambda_c = 0.0
        self.lambda_r = 0.0

    def fit(self, X, dice_k1, dice_k3, dice_k6, risk) -> None:  # noqa: D401
        pass

    def predict_k(self, X: np.ndarray) -> np.ndarray:
        return np.full(len(X), self.fixed_k, dtype=np.int64)


class M1Threshold(M1Model):
    """M1-3 handcrafted threshold on ``matching_map_disagreement``.

    Policy: if ``disagreement > threshold`` use k=6, else k=1. The threshold
    is swept from the 10th to 90th percentile of the training disagreement and
    selected to maximize mean U on train (with the model's lambda_c / lambda_r).
    """

    def __init__(self, name: str, lambda_c: float, lambda_r: float):
        self.name = name
        self.model_type = "threshold"
        self.lambda_c = lambda_c
        self.lambda_r = lambda_r
        self.threshold = 0.0
        self.best_mean_u = float("-inf")

    def fit(self, X, dice_k1, dice_k3, dice_k6, risk) -> None:
        disagreement = X[:, 0].astype(np.float64)
        if len(disagreement) == 0:
            self.threshold = 0.0
            return
        lo = float(np.percentile(disagreement, THRESHOLD_SWEEP_LO_PCT))
        hi = float(np.percentile(disagreement, THRESHOLD_SWEEP_HI_PCT))
        if hi <= lo:
            hi = lo + 1.0
        thresholds = np.linspace(lo, hi, THRESHOLD_SWEEP_N)
        best_u = float("-inf")
        best_thr = float(thresholds[0])
        for thr in thresholds:
            sel_k = np.where(disagreement > thr, 6, 1).astype(np.int64)
            sel_dice = _select_dice(sel_k, dice_k1, dice_k3, dice_k6)
            u = compute_utility(sel_dice, sel_k, risk, self.lambda_c, self.lambda_r)
            mu = float(np.mean(u))
            if mu > best_u:
                best_u = mu
                best_thr = float(thr)
        self.threshold = best_thr
        self.best_mean_u = best_u

    def predict_k(self, X: np.ndarray) -> np.ndarray:
        disagreement = X[:, 0].astype(np.float64)
        return np.where(disagreement > self.threshold, 6, 1).astype(np.int64)


class M1Sklearn(M1Model):
    """Sklearn classifier predicting best k (M1-4 logistic, M1-5 gradient boosting)."""

    def __init__(
        self,
        name: str,
        estimator: Any,
        lambda_c: float,
        lambda_r: float,
        model_type: str = "sklearn",
    ):
        self.name = name
        self.model_type = model_type
        self.estimator = estimator
        self.scaler = StandardScaler()
        self.lambda_c = lambda_c
        self.lambda_r = lambda_r
        self.best_mean_u = float("-inf")

    def fit(self, X, dice_k1, dice_k3, dice_k6, risk) -> None:
        best_k = compute_best_k(
            dice_k1, dice_k3, dice_k6, risk, self.lambda_c, self.lambda_r,
        )
        Xs = self.scaler.fit_transform(X)
        # Guard: if only a single class is present, still fit (sklearn handles it).
        self.estimator.fit(Xs, best_k)

    def predict_k(self, X: np.ndarray) -> np.ndarray:
        Xs = self.scaler.transform(X)
        pred = self.estimator.predict(Xs)
        # Map any unexpected labels back into {1, 3, 6} (clip to nearest valid k).
        out = np.empty(len(pred), dtype=np.int64)
        for i, p in enumerate(pred):
            p_int = int(round(float(p)))
            if p_int in K_TO_INDEX:
                out[i] = p_int
            elif p_int <= 1:
                out[i] = 1
            elif p_int <= 3:
                out[i] = 3
            else:
                out[i] = 6
        return out


def build_baseline_models() -> list[M1Model]:
    return [
        M1Baseline("M1-0_always_k1", 1),
        M1Baseline("M1-1_always_k3", 3),
        M1Baseline("M1-2_always_k6", 6),
    ]


def _logistic_factory(lambda_c: float, lambda_r: float) -> M1Sklearn:
    return M1Sklearn(
        "M1-4_logistic_regression",
        LogisticRegression(
            C=1.0, max_iter=1000, random_state=RANDOM_STATE, solver="lbfgs",
        ),
        lambda_c, lambda_r,
        model_type="logistic",
    )


def _gradient_boosting_factory(lambda_c: float, lambda_r: float) -> M1Sklearn:
    return M1Sklearn(
        "M1-5_gradient_boosting",
        GradientBoostingClassifier(
            n_estimators=100, max_depth=3, random_state=RANDOM_STATE,
        ),
        lambda_c, lambda_r,
        model_type="gradient_boosting",
    )


def _threshold_factory(lambda_c: float, lambda_r: float) -> M1Threshold:
    return M1Threshold("M1-3_handcrafted_threshold", lambda_c, lambda_r)


# ---------------------------------------------------------------------------
# Inner CV lambda selection (section 9.5)
# ---------------------------------------------------------------------------

def select_lambdas_cv(
    model_factory: Callable[[float, float], M1Model],
    X: np.ndarray,
    dice_k1: np.ndarray,
    dice_k3: np.ndarray,
    dice_k6: np.ndarray,
    risk: np.ndarray,
    n_folds: int = N_INNER_FOLDS,
) -> tuple[float, float, float]:
    """5-fold inner CV on train: select (lambda_c, lambda_r) maximizing mean U.

    Within each fold the model is trained on the train partition (its labels /
    threshold derived from that partition's Dice + risk + the candidate
    lambdas) and evaluated by mean U on the held-out partition.
    """
    if len(X) < n_folds:
        n_folds = max(2, len(X))
    kf = KFold(n_splits=n_folds, shuffle=True, random_state=RANDOM_STATE)
    best_lc = LAMBDA_C_GRID[0]
    best_lr = LAMBDA_R_GRID[0]
    best_mean_u = float("-inf")
    for lc in LAMBDA_C_GRID:
        for lr in LAMBDA_R_GRID:
            fold_us: list[float] = []
            for train_idx, val_idx in kf.split(X):
                model = model_factory(lc, lr)
                model.fit(
                    X[train_idx],
                    dice_k1[train_idx],
                    dice_k3[train_idx],
                    dice_k6[train_idx],
                    risk[train_idx],
                )
                pred_k = model.predict_k(X[val_idx])
                pred_dice = _select_dice(
                    pred_k,
                    dice_k1[val_idx],
                    dice_k3[val_idx],
                    dice_k6[val_idx],
                )
                u = compute_utility(
                    pred_dice, pred_k, risk[val_idx], lc, lr,
                )
                fold_us.append(float(np.mean(u)) if len(u) else 0.0)
            mean_u = float(np.mean(fold_us)) if fold_us else 0.0
            if mean_u > best_mean_u:
                best_mean_u = mean_u
                best_lc = lc
                best_lr = lr
    return best_lc, best_lr, best_mean_u


# ---------------------------------------------------------------------------
# Evaluation metrics
# ---------------------------------------------------------------------------

def compute_cvar_0_1(dice: np.ndarray) -> float:
    """CVaR_0.1 = mean of the bottom 10% of per-episode Dice values."""
    n = len(dice)
    if n == 0:
        return 0.0
    sorted_dice = np.sort(dice.astype(np.float64))
    k = max(1, int(np.ceil(CVAR_QUANTILE * n)))
    return float(np.mean(sorted_dice[:k]))


def evaluate_model(
    model: M1Model,
    X: np.ndarray,
    dice_k1: np.ndarray,
    dice_k3: np.ndarray,
    dice_k6: np.ndarray,
    risk: np.ndarray,
    eval_lambda_c: float = EVAL_LAMBDA_C,
    eval_lambda_r: float = EVAL_LAMBDA_R,
) -> dict[str, Any]:
    """Evaluate a model on the given data; return Dice / avg_k / CVaR / CFR / cost / U."""
    pred_k = model.predict_k(X)
    pred_dice = _select_dice(pred_k, dice_k1, dice_k3, dice_k6)
    mean_dice = float(np.mean(pred_dice)) if len(pred_dice) else 0.0
    avg_k = float(np.mean(pred_k)) if len(pred_k) else 0.0
    cvar = compute_cvar_0_1(pred_dice)
    cfr = float(np.mean(pred_dice < CATASTROPHIC_DICE_THRESHOLD)) if len(pred_dice) else 0.0
    cost = float(np.mean(pred_k / 6.0)) if len(pred_k) else 0.0
    u = compute_utility(pred_dice, pred_k, risk, eval_lambda_c, eval_lambda_r)
    mean_u = float(np.mean(u)) if len(u) else 0.0
    return {
        "model_name": model.name,
        "model_type": model.model_type,
        "lambda_c": model.lambda_c,
        "lambda_r": model.lambda_r,
        "mean_dice": mean_dice,
        "avg_k": avg_k,
        "cvar_0_1": cvar,
        "cfr": cfr,
        "cost": cost,
        "mean_u": mean_u,
        "pred_k": pred_k,
        "pred_dice": pred_dice,
    }


# ---------------------------------------------------------------------------
# Gate evaluation (section 9.6)
# ---------------------------------------------------------------------------

def evaluate_gate(
    best_model: M1Model,
    best_result: dict[str, Any],
    baseline_k6: dict[str, Any],
    baseline_k3: dict[str, Any],
    train_rows: list[dict[str, Any]],
    val_rows: list[dict[str, Any]],
) -> tuple[dict[str, Any], list[tuple[str, bool, str]]]:
    """Evaluate the M1 gate (cost-saving mode OR quality-cost mode)."""
    policy = best_result
    cond_list: list[tuple[str, bool, str]] = []

    # --- Cost-saving mode (vs k=6) ---
    dice_diff_k6 = policy["mean_dice"] - baseline_k6["mean_dice"]
    cs1_pass = dice_diff_k6 >= -GATE_DICE_TOLERANCE_K6
    cond_list.append((
        "cs1_dice_not_below_k6_by_0p003",
        cs1_pass,
        f"Dice diff = {dice_diff_k6:+.6f} "
        f"(policy={policy['mean_dice']:.6f}, k6={baseline_k6['mean_dice']:.6f})",
    ))

    cvar_diff_k6 = policy["cvar_0_1"] - baseline_k6["cvar_0_1"]
    cs2_pass = cvar_diff_k6 >= -GATE_CVAR_TOLERANCE_K6
    cond_list.append((
        "cs2_cvar_not_decrease_by_0p005",
        cs2_pass,
        f"CVaR diff = {cvar_diff_k6:+.6f} "
        f"(policy={policy['cvar_0_1']:.6f}, k6={baseline_k6['cvar_0_1']:.6f})",
    ))

    cfr_diff_k6 = policy["cfr"] - baseline_k6["cfr"]
    cs3_pass = cfr_diff_k6 <= 0.0
    cond_list.append((
        "cs3_cfr_not_increase",
        cs3_pass,
        f"CFR diff = {cfr_diff_k6:+.6f} "
        f"(policy={policy['cfr']:.6f}, k6={baseline_k6['cfr']:.6f})",
    ))

    avg_k = policy["avg_k"]
    reduction_pct = (1.0 - avg_k / 6.0) * 100.0 if baseline_k6["avg_k"] > 0 else 0.0
    cs4_pass = avg_k < GATE_AVG_K_COST_SAVING
    cond_list.append((
        "cs4_avg_ref_count_reduce_25pct",
        cs4_pass,
        f"avg_k = {avg_k:.4f}, reduction = {reduction_pct:.1f}% "
        f"(threshold < {GATE_AVG_K_COST_SAVING})",
    ))

    cost_saving_pass = cs1_pass and cs2_pass and cs3_pass and cs4_pass

    # --- Quality-cost mode (vs k=3) ---
    dice_diff_k3 = policy["mean_dice"] - baseline_k3["mean_dice"]
    in_k3_band = GATE_AVG_K_QC_LO <= avg_k <= GATE_AVG_K_QC_HI
    qc1_pass = in_k3_band and (dice_diff_k3 >= GATE_DICE_GAIN_K3)
    if not in_k3_band:
        qc1_detail = (
            f"Dice diff vs k=3 = {dice_diff_k3:+.6f} but avg_k = {avg_k:.4f} "
            f"not in [{GATE_AVG_K_QC_LO}, {GATE_AVG_K_QC_HI}]"
        )
    else:
        qc1_detail = (
            f"Dice diff vs k=3 = {dice_diff_k3:+.6f} "
            f"(policy={policy['mean_dice']:.6f}, k3={baseline_k3['mean_dice']:.6f}, "
            f"required >= {GATE_DICE_GAIN_K3})"
        )
    cond_list.append((
        "qc1_dice_ge_k3_plus_0p0075",
        qc1_pass,
        qc1_detail,
    ))

    cvar_diff_k3 = policy["cvar_0_1"] - baseline_k3["cvar_0_1"]
    qc2_pass = cvar_diff_k3 > 0.0
    cond_list.append((
        "qc2_cvar_improve",
        qc2_pass,
        f"CVaR diff vs k=3 = {cvar_diff_k3:+.6f} "
        f"(policy={policy['cvar_0_1']:.6f}, k3={baseline_k3['cvar_0_1']:.6f})",
    ))

    cfr_diff_k3 = policy["cfr"] - baseline_k3["cfr"]
    qc3_pass = cfr_diff_k3 <= 0.0
    cond_list.append((
        "qc3_cfr_not_increase",
        qc3_pass,
        f"CFR diff vs k=3 = {cfr_diff_k3:+.6f} "
        f"(policy={policy['cfr']:.6f}, k3={baseline_k3['cfr']:.6f})",
    ))

    quality_cost_pass = qc1_pass and qc2_pass and qc3_pass

    decision = GATE_PASS if (cost_saving_pass or quality_cost_pass) else GATE_NO_GAIN

    summary = {
        "gate": "Phase T WP3 M1 Dynamic Reference Budget Gate",
        "n_train_episodes": len(train_rows),
        "n_val_episodes": len(val_rows),
        "n_train_queries": len({r["query_case_id"] for r in train_rows}),
        "n_val_queries": len({r["query_case_id"] for r in val_rows}),
        "best_model": best_model.name,
        "selected_lambda_c": best_model.lambda_c,
        "selected_lambda_r": best_model.lambda_r,
        "baseline_k6": {
            "mean_dice": baseline_k6["mean_dice"],
            "cvar_0_1": baseline_k6["cvar_0_1"],
            "cfr": baseline_k6["cfr"],
            "avg_k": baseline_k6["avg_k"],
        },
        "baseline_k3": {
            "mean_dice": baseline_k3["mean_dice"],
            "cvar_0_1": baseline_k3["cvar_0_1"],
            "cfr": baseline_k3["cfr"],
            "avg_k": baseline_k3["avg_k"],
        },
        "policy": {
            "mean_dice": policy["mean_dice"],
            "cvar_0_1": policy["cvar_0_1"],
            "cfr": policy["cfr"],
            "avg_k": policy["avg_k"],
        },
        "conditions": {
            "cost_saving_mode": {
                "cs1_dice_not_below_k6_by_0p003": {
                    "pass": cs1_pass,
                    "details": cond_list[0][2],
                },
                "cs2_cvar_not_decrease_by_0p005": {
                    "pass": cs2_pass,
                    "details": cond_list[1][2],
                },
                "cs3_cfr_not_increase": {
                    "pass": cs3_pass,
                    "details": cond_list[2][2],
                },
                "cs4_avg_ref_count_reduce_25pct": {
                    "pass": cs4_pass,
                    "details": cond_list[3][2],
                },
                "mode_pass": cost_saving_pass,
            },
            "quality_cost_mode": {
                "qc1_dice_ge_k3_plus_0p0075": {
                    "pass": qc1_pass,
                    "details": cond_list[4][2],
                },
                "qc2_cvar_improve": {
                    "pass": qc2_pass,
                    "details": cond_list[5][2],
                },
                "qc3_cfr_not_increase": {
                    "pass": qc3_pass,
                    "details": cond_list[6][2],
                },
                "mode_pass": quality_cost_pass,
            },
        },
        "decision": decision,
    }
    return summary, cond_list


