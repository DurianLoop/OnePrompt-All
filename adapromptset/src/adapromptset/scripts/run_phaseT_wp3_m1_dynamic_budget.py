# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

FEATURE_COLS: tuple[str, ...] = (
    "matching_map_disagreement",
    "candidate_jaccard_mean_k1",
    "prompt_overlap_mean_k1",
    "prediction_jaccard_k1_within",
)

K_VALUES: tuple[int, ...] = (1, 3, 6)
K_TO_INDEX: dict[int, int] = {1: 0, 3: 1, 6: 2}

# Normalized matching cost C(k) = k / 6.
def cost_of(k: int) -> float:
    return k / 6.0


# Hyperparameter grid (section 9.5).
LAMBDA_C_GRID: tuple[float, ...] = (0.0, 0.01, 0.025, 0.05)
LAMBDA_R_GRID: tuple[float, ...] = (0.0, 0.25, 0.5, 1.0)

# Fixed evaluation lambdas (level playing field for model selection / best_k).
EVAL_LAMBDA_C = 0.025
EVAL_LAMBDA_R = 0.5

# Catastrophic failure threshold (Dice < this -> catastrophic).
CATASTROPHIC_DICE_THRESHOLD = 0.1

# CVaR tail fraction.
CVAR_QUANTILE = 0.10

# Inner CV folds.
N_INNER_FOLDS = 5

# Gate thresholds (section 9.6).
GATE_DICE_TOLERANCE_K6 = 0.003       # cost-saving: Dice not below k=6 by more than this
GATE_CVAR_TOLERANCE_K6 = 0.005       # cost-saving: CVaR not decrease by more than this
GATE_AVG_K_COST_SAVING = 4.5         # cost-saving: avg_k < 4.5 (>= 25% reduction vs 6.0)
GATE_AVG_K_QC_LO = 2.5               # quality-cost: avg_k in [2.5, 3.5]
GATE_AVG_K_QC_HI = 3.5
GATE_DICE_GAIN_K3 = 0.0075           # quality-cost: Dice >= k=3 + this

# M1-3 threshold sweep percentile range.
THRESHOLD_SWEEP_LO_PCT = 10
THRESHOLD_SWEEP_HI_PCT = 90
THRESHOLD_SWEEP_N = 50

RANDOM_STATE = 20260723

GATE_PASS = "PHASET_M1_DYNAMIC_BUDGET_PASS"
GATE_NO_GAIN = "PHASET_M1_DYNAMIC_BUDGET_NO_GAIN"


