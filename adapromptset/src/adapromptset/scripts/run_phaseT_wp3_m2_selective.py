def evaluate_all_models(
    models: list[M2Model],
    train_rows: list[dict[str, Any]],
    val_rows: list[dict[str, Any]],
    train_labels: dict[str, np.ndarray],
    val_labels: dict[str, np.ndarray],
    train_label_key: str = "catastrophic",
) -> tuple[list[dict[str, Any]], M2Model | None, dict[str, Any] | None]:
    """Train and evaluate all M2 models. Returns (results, best_model, best_result).

    Parameters
    ----------
    train_label_key : str
        Which train label to fit on: "instability" or "catastrophic".
        The models are evaluated on BOTH labels regardless of training label.
    """
    X_train = episodes_to_matrix(train_rows)
    X_val = episodes_to_matrix(val_rows)
    y_train = train_labels[train_label_key]
    y_val_instab = val_labels["instability"]
    y_val_cat = val_labels["catastrophic"]
    val_mean_dice = np.asarray(
        [r["mean_dice_k1"] for r in val_rows], dtype=np.float64
    )

    results: list[dict[str, Any]] = []
    for model in models:
        print(f"[phaseT-M2] training {model.name} ...")
        res = _evaluate_single(
            model, X_train, y_train, X_val, y_val_instab, y_val_cat,
            val_mean_dice, val_rows, train_label_key,
        )
        results.append(res)
        print(
            f"[phaseT-M2]   {model.name}: AUROC={res['auroc_instability']:.4f} "
            f"AUPRC_instab={res['auprc_instability']:.4f} "
            f"AUPRC_cat={res['auprc_catastrophic']:.4f} "
            f"ECE={res['ece']:.4f} (cal={res['ece_calibrated']:.4f}) "
            f"CFR_red@80={res['cfr_reduction_at_80']:.4f} "
            f"Dice_chg@80={res['dice_change_at_80']:.6f}"
        )

    # Select best model by the training-label-appropriate metric.
    if train_label_key == "instability":
        best_result = max(results, key=lambda r: r["auroc_instability"])
        best_metric = f"instability AUROC={best_result['auroc_instability']:.4f}"
    else:
        best_result = max(results, key=lambda r: r["auprc_catastrophic"])
        best_metric = f"catastrophic AUPRC={best_result['auprc_catastrophic']:.4f}"
    best_idx = results.index(best_result)
    best_model = models[best_idx]
    print(f"[phaseT-M2] best model ({train_label_key}): {best_model.name} "
          f"({best_metric})")
    return results, best_model, best_result


def _evaluate_single(
    model: M2Model,
    X_train: np.ndarray,
    y_train: np.ndarray,
    X_val: np.ndarray,
    y_val_instab: np.ndarray,
    y_val_cat: np.ndarray,
    val_mean_dice: np.ndarray,
    val_rows: list[dict[str, Any]],
    train_label_key: str = "catastrophic",
) -> dict[str, Any]:
    """Train and evaluate one model (with proper query-level aggregation)."""
    model.fit(X_train, y_train)
    # ECE label follows the training label (model predicts that concept).
    y_val_ece = y_val_cat if train_label_key == "catastrophic" else y_val_instab

    # Predictions
    val_risk_raw = model.predict_risk(X_val)
    train_risk = model.predict_risk(X_train)

    # AUROC / AUPRC (episode level)
    auroc_instab = safe_auroc(y_val_instab, val_risk_raw)
    auprc_instab = safe_auprc(y_val_instab, val_risk_raw)
    auprc_cat = safe_auprc(y_val_cat, val_risk_raw)

    # ECE (computed against the training-label-matched validation label)
    ece, calib_bins = compute_ece(y_val_ece, val_risk_raw)

    # Platt scaling if ECE > 0.10
    platt = None
    ece_calibrated = ece
    val_risk = val_risk_raw
    val_risk_calibrated = val_risk_raw
    if ece > GATE_ECE_THRESHOLD:
        platt = fit_platt_scaler(train_risk, y_train)
        if platt is not None:
            val_risk_calibrated = apply_platt_scaler(platt, val_risk_raw)
            ece_calibrated, _ = compute_ece(y_val_ece, val_risk_calibrated)
            if ece_calibrated < ece:
                val_risk = val_risk_calibrated
                ece = ece_calibrated
            else:
                platt = None
                val_risk_calibrated = val_risk_raw

    # Risk-coverage curve (use calibrated risk if applied)
    rc_rows = compute_risk_coverage(val_risk, val_mean_dice, y_val_cat)

    # Metrics at 80% coverage
    m80 = metrics_at_coverage(val_risk, val_mean_dice, y_val_cat, GATE_COVERAGE)

    # Query-level aggregation (proper)
    query_rows, q_risk, q_instab, q_cat = _aggregate_queries(
        val_rows, val_risk, val_mean_dice,
    )
    q_auroc = safe_auroc(q_instab, q_risk)
    q_auprc_cat = safe_auprc(q_cat, q_risk)
    q_mean_dice = np.asarray([qr["mean_dice"] for qr in query_rows], dtype=np.float64)
    q_rc = compute_risk_coverage(q_risk, q_mean_dice, q_cat)
    q_m80 = metrics_at_coverage(q_risk, q_mean_dice, q_cat, GATE_COVERAGE)

    return {
        "model_name": model.name,
        "model_type": model.model_type,
        "auroc_instability": auroc_instab,
        "auprc_instability": auprc_instab,
        "auprc_catastrophic": auprc_cat,
        "ece": ece,
        "ece_calibrated": ece_calibrated,
        "platt_applied": platt is not None,
        "cfr_no_abstention": m80["cfr_all"],
        "cfr_at_80_coverage": m80["cfr"],
        "cfr_reduction_at_80": m80["cfr_reduction"],
        "dice_no_abstention": m80["dice_all"],
        "dice_at_80_coverage": m80["dice"],
        "dice_change_at_80": m80["dice_change"],
        "auroc_instability_query": q_auroc,
        "auprc_catastrophic_query": q_auprc_cat,
        "cfr_reduction_at_80_query": q_m80["cfr_reduction"],
        "dice_change_at_80_query": q_m80["dice_change"],
        "best_threshold": getattr(model, "best_threshold", None),
        "best_threshold_raw": getattr(model, "best_threshold_raw", None),
        "val_risk": val_risk,
        "val_risk_calibrated": val_risk_calibrated,
        "calibration_bins": calib_bins,
        "risk_coverage": rc_rows,
        "query_risk_coverage": q_rc,
    }


def _aggregate_queries(
    val_rows: list[dict[str, Any]],
    val_risk: np.ndarray,
    val_mean_dice: np.ndarray,
) -> tuple[list[dict[str, Any]], np.ndarray, np.ndarray, np.ndarray]:
    """Aggregate val episodes to query level."""
    by_query: dict[str, list[int]] = {}
    for i, r in enumerate(val_rows):
        by_query.setdefault(r["query_case_id"], []).append(i)
    query_rows: list[dict[str, Any]] = []
    q_risk: list[float] = []
    q_instab: list[int] = []
    q_cat: list[int] = []
    for qid in sorted(by_query):
        idxs = by_query[qid]
        eps = [val_rows[i] for i in idxs]
        mean_dice = float(np.mean([e["mean_dice_k1"] for e in eps]))
        mean_gap = float(np.mean([e["best_worst_gap_k1"] for e in eps]))
        mean_risk = float(np.mean([val_risk[i] for i in idxs]))
        query_rows.append({
            "query_case_id": qid,
            "mean_dice": mean_dice,
            "mean_gap": mean_gap,
            "mean_risk": mean_risk,
            "n_episodes": len(eps),
        })
        q_risk.append(mean_risk)
        q_instab.append(int(mean_gap >= INSTABILITY_GAP_THRESHOLD))
        q_cat.append(int(mean_dice < CATASTROPHIC_DICE_THRESHOLD))
    return (
        query_rows,
        np.asarray(q_risk, dtype=np.float64),
        np.asarray(q_instab, dtype=np.int64),
        np.asarray(q_cat, dtype=np.int64),
    )


