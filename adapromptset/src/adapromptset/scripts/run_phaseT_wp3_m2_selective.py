"""Phase T WP3 M2 Instability-Aware Selective Prediction.

Trains and evaluates M2 models that predict per-episode instability risk from
test-time-safe features. Episode data is generated by
``run_phaseT_wp3_trainval_benchmark.py`` and stored as
``phase2_episode_instability.csv`` in the train / val report directories.

Pipeline::

    1. Load train / val episode data (phase2_episode_instability.csv).
    2. Construct labels on train (instability, catastrophic, tail-risk).
    3. Train M2-0 .. M2-4 on train (4 features -> instability label).
    4. Evaluate each model on val (AUROC, AUPRC, ECE, risk-coverage curve).
    5. Select best model (highest val AUROC).
    6. Evaluate M2 gate conditions (section 10.5).
    7. Write outputs (CSVs, JSON, MD, pickle).

Models (section 10.3)::

    M2-0  Entropy threshold      (single feature threshold, matching_map_disagreement as entropy proxy)
    M2-1  Disagreement threshold  (single feature threshold on matching_map_disagreement)
    M2-2  Logistic regression     (sklearn LogisticRegression on 4 features)
    M2-3  Gradient boosting       (sklearn GradientBoostingClassifier on 4 features)
    M2-4  Small MLP               (sklearn MLPClassifier on 4 features, hidden=(16,8), max_iter=500)

Features (4 test-time-safe)::

    matching_map_disagreement
    candidate_jaccard_mean_k1
    prompt_overlap_mean_k1
    prediction_jaccard_k1_within

CLI::

    python src/adapromptset/scripts/run_phaseT_wp3_m2_selective.py \
        --train-dir reports/phaseT_wp3_train \
        --val-dir reports/phaseT_wp3_validation \
        --out-dir reports/phaseT_wp3_m2 \
        --smoke
"""

