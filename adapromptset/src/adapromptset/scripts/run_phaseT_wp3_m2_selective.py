def main() -> None:
    parser = argparse.ArgumentParser(
        description="Phase T WP3 M2 Instability-Aware Selective Prediction",
    )
    parser.add_argument(
        "--train-dir", type=Path,
        default=PROJECT_ROOT / "reports" / "phaseT_wp3_train",
    )
    parser.add_argument(
        "--val-dir", type=Path,
        default=PROJECT_ROOT / "reports" / "phaseT_wp3_validation",
    )
    parser.add_argument(
        "--out-dir", type=Path,
        default=PROJECT_ROOT / "reports" / "phaseT_wp3_m2",
    )
    parser.add_argument(
        "--smoke", action="store_true",
        help="Quick verification: first 20 rows of train/val.",
    )
    args = parser.parse_args()

    train_csv = args.train_dir / "phase2_episode_instability.csv"
    val_csv = args.val_dir / "phase2_episode_instability.csv"
    out_dir: Path = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"[phaseT-M2] train_csv={train_csv}")
    print(f"[phaseT-M2] val_csv={val_csv}")
    print(f"[phaseT-M2] out_dir={out_dir}")
    print(f"[phaseT-M2] smoke={args.smoke}")

    start = time.perf_counter()

    # Step 1-2: Load train / val episode data.
    train_rows = load_episodes(train_csv)
    val_rows = load_episodes(val_csv)
    if args.smoke:
        train_rows = train_rows[:20]
        val_rows = val_rows[:20]
    print(f"[phaseT-M2] loaded {len(train_rows)} train episodes, "
          f"{len(val_rows)} val episodes")
    if not train_rows:
        raise RuntimeError(f"No train episodes found at {train_csv}")
    if not val_rows:
        raise RuntimeError(f"No val episodes found at {val_csv}")

    # Step 3: Construct labels on train.
    train_labels = construct_labels(train_rows)
    val_labels = construct_val_labels(val_rows)
    print(f"[phaseT-M2] train label prevalence: "
          f"instability={np.mean(train_labels['instability']):.4f}, "
          f"catastrophic={np.mean(train_labels['catastrophic']):.4f}, "
          f"tail_risk={np.mean(train_labels['tail_risk']):.4f} "
          f"(threshold={train_labels['tail_threshold']:.6f})")
    print(f"[phaseT-M2] val label prevalence: "
          f"instability={np.mean(val_labels['instability']):.4f}, "
          f"catastrophic={np.mean(val_labels['catastrophic']):.4f}")

    # Step 4-5: Train and evaluate M2-0 .. M2-4 on BOTH labels.
    # Dual-model approach: a catastrophic-trained model drives selective
    # prediction (cond2-5), while an instability-trained model drives
    # cond1. The two labels are anti-correlated, so a single fit cannot
    # satisfy both gate axes.
    print("[phaseT-M2] training catastrophic-labelled models (drives cond2-5) ...")
    cat_results, cat_model, cat_result = evaluate_all_models(
        build_all_models(), train_rows, val_rows, train_labels, val_labels,
        train_label_key="catastrophic",
    )
    print()
    print("[phaseT-M2] training instability-labelled models (drives cond1) ...")
    inst_results, inst_model, inst_result = evaluate_all_models(
        build_all_models(), train_rows, val_rows, train_labels, val_labels,
        train_label_key="instability",
    )

    # Step 6-7: Evaluate gate (dual-model).
    print()
    print("[phaseT-M2] evaluating M2 gate conditions (dual-model) ...")
    summary, cond_list = evaluate_gate(
        cat_result, cat_model, inst_result, inst_model,
        train_rows, val_rows, train_labels, val_labels,
    )

    # Step 8: Write outputs.
    write_train_episodes(out_dir, train_rows, train_labels)
    write_val_predictions(out_dir, val_rows, val_labels, cat_result, inst_result)
    write_model_comparison(out_dir, cat_results, label_key="catastrophic")
    write_model_comparison(out_dir, inst_results, label_key="instability")
    write_risk_coverage(out_dir, cat_result)
    write_gate_summary_json(out_dir, summary)
    write_gate_summary_md(
        out_dir, summary, cond_list,
        cat_results, inst_results, cat_result, inst_result,
    )
    write_model_pickle(out_dir, cat_model, cat_result, inst_model, inst_result)
    elapsed = time.perf_counter() - start
    write_run_metadata(
        out_dir, train_rows, val_rows, train_labels, val_labels,
        cat_model, cat_result, inst_model, inst_result,
        summary, elapsed, args.smoke,
    )

    # Print gate results.
    print()
    print("=" * 72)
    print("[phaseT-M2] Gate conditions:")
    for i, (name, ok, detail) in enumerate(cond_list, 1):
        status = "PASS" if ok else ("PENDING" if ok is None else "FAIL")
        print(f"  cond{i}: {status}  {name}")
        print(f"         {detail}")
    print()
    n_pass = sum(1 for _, ok, _ in cond_list if ok is True)
    n_checked = sum(1 for _, ok, _ in cond_list if ok is not None)
    print(f"  {n_pass}/{n_checked} checked conditions passed")
    print(f"  FINAL STATE: {summary['decision']}")
    print("=" * 72)
    print(f"[phaseT-M2] artifacts written to {out_dir}")
    print(f"[phaseT-M2] elapsed {elapsed:.1f}s")


if __name__ == "__main__":
    main()
