def evaluate_gate(
    cat_result: dict[str, Any],
    cat_model: M2Model,
    inst_result: dict[str, Any],
    inst_model: M2Model,
    train_rows: list[dict[str, Any]],
    val_rows: list[dict[str, Any]],
    train_labels: dict[str, np.ndarray],
    val_labels: dict[str, np.ndarray],
) -> tuple[dict[str, Any], list[tuple[str, bool | None, str]]]:
    """Evaluate the 6 M2 gate conditions on validation.

    Uses the dual-model approach:
    - cond1 (instability AUROC): from the instability-trained model.
    - cond2-5 (catastrophic AUPRC, ECE, CFR, Dice): from the
      catastrophic-trained model (drives selective prediction).
    """
    cond_list: list[tuple[str, bool | None, str]] = []

    prevalence_instab = float(np.mean(val_labels["instability"]))
    prevalence_cat = float(np.mean(val_labels["catastrophic"]))

    # cond1: instability AUROC >= 0.70 (from instability-trained model)
    auroc = inst_result["auroc_instability"]
    cond1_pass = auroc >= GATE_AUROC_THRESHOLD
    cond_list.append((
        "cond1_instability_auroc_ge_0p70",
        cond1_pass,
        f"AUROC = {auroc:.4f} (query-level: {inst_result['auroc_instability_query']:.4f}) "
        f"[instability-trained model: {inst_model.name}]",
    ))

    # cond2: catastrophic-risk AUPRC > prevalence (from catastrophic-trained model)
    auprc_cat = cat_result["auprc_catastrophic"]
    cond2_pass = auprc_cat > prevalence_cat
    cond_list.append((
        "cond2_catastrophic_auprc_gt_prevalence",
        cond2_pass,
        f"AUPRC = {auprc_cat:.4f}, prevalence = {prevalence_cat:.4f} "
        f"[catastrophic-trained model: {cat_model.name}]",
    ))

    # cond3: ECE <= 0.10 (or <= 0.08 after calibration) — from catastrophic model
    ece = cat_result["ece"]
    ece_cal = cat_result["ece_calibrated"]
    platt_applied = cat_result["platt_applied"]
    if ece <= GATE_ECE_THRESHOLD:
        cond3_pass = True
        cond3_detail = f"ECE = {ece:.4f} [catastrophic model]"
    elif platt_applied and ece_cal <= GATE_ECE_CALIBRATED_THRESHOLD:
        cond3_pass = True
        cond3_detail = f"ECE = {ece:.4f}, after calibration ECE = {ece_cal:.4f} [catastrophic model]"
    else:
        cond3_pass = False
        cond3_detail = (
            f"ECE = {ece:.4f}"
            + (f", after calibration ECE = {ece_cal:.4f}" if platt_applied else "")
            + " [catastrophic model]"
        )
    cond_list.append((
        "cond3_ece_le_0p10",
        cond3_pass,
        cond3_detail,
    ))

    # cond4: CFR relative reduction >= 30% at 80% coverage (from catastrophic model)
    cfr_red = cat_result["cfr_reduction_at_80"]
    cfr_all = cat_result["cfr_no_abstention"]
    if cfr_all == 0.0:
        # No catastrophic failures to reduce; vacuously passes.
        cond4_pass = True
        cond4_detail = (
            f"CFR reduction = {cfr_red:.4f} (no catastrophic failures in val; "
            f"vacuously satisfied)"
        )
    else:
        cond4_pass = cfr_red >= GATE_CFR_REDUCTION_THRESHOLD
        cond4_detail = (
            f"CFR reduction = {cfr_red * 100:.1f}% "
            f"(CFR all={cfr_all:.4f}, CFR@80%={cat_result['cfr_at_80_coverage']:.4f})"
        )
    cond_list.append((
        "cond4_cfr_reduction_30pct_at_80pct_coverage",
        cond4_pass,
        cond4_detail,
    ))

    # cond5: mean Dice not decrease at 80% coverage (from catastrophic model)
    dice_change = cat_result["dice_change_at_80"]
    cond5_pass = dice_change >= 0.0
    cond_list.append((
        "cond5_dice_not_decrease_at_80pct_coverage",
        cond5_pass,
        f"Dice change = {dice_change:+.6f} "
        f"(Dice all={cat_result['dice_no_abstention']:.6f}, "
        f"Dice@80%={cat_result['dice_at_80_coverage']:.6f}) "
        f"[catastrophic model]",
    ))

    # cond6: holdout direction consistent (PENDING - requires holdout run)
    cond_list.append((
        "cond6_holdout_direction_consistent",
        None,
        "PENDING - requires holdout run (holdout benchmark not yet executed)",
    ))

    # Decision: conditions 1-5 all pass (cond6 is PENDING).
    conds_1_5 = [c for c in cond_list[:5]]
    all_pass_1_5 = all(ok for _, ok, _ in conds_1_5)
    decision = GATE_PASS if all_pass_1_5 else GATE_NO_GAIN

    n_train_queries = len({r["query_case_id"] for r in train_rows})
    n_val_queries = len({r["query_case_id"] for r in val_rows})

    summary = {
        "gate": "Phase T WP3 M2 Selective Prediction Gate",
        "n_train_episodes": len(train_rows),
        "n_val_episodes": len(val_rows),
        "n_train_queries": n_train_queries,
        "n_val_queries": n_val_queries,
        "best_model_cat": cat_model.name,
        "best_model_inst": inst_model.name,
        "prevalence_instability": round(prevalence_instab, 6),
        "prevalence_catastrophic": round(prevalence_cat, 6),
        "tail_risk_threshold": round(float(train_labels["tail_threshold"]), 6),
        "conditions": {
            name: {"pass": ok, "details": detail}
            for name, ok, detail in cond_list
        },
        "decision": decision,
    }
    return summary, cond_list


