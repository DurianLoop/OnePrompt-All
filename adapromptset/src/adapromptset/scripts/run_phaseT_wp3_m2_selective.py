def _model_to_bundle(
    model: M2Model,
    feature_cols: tuple[str, ...],
    result: dict[str, Any],
) -> dict[str, Any]:
    """Serialise a single M2 model + its Platt calibrator flag."""
    bundle: dict[str, Any] = {
        "model_name": model.name,
        "model_type": model.model_type,
        "feature_cols": list(feature_cols),
    }
    if model.model_type == "threshold":
        bundle["feature_index"] = model.feature_index
        bundle["feature_name"] = model.feature_name
        bundle["fmin"] = model.fmin
        bundle["fmax"] = model.fmax
        bundle["best_threshold"] = model.best_threshold
        bundle["best_threshold_raw"] = model.best_threshold_raw
        bundle["scaler"] = None
        bundle["estimator"] = None
    else:
        bundle["scaler"] = model.scaler
        bundle["estimator"] = model.estimator
        bundle["feature_index"] = None
        bundle["feature_name"] = None
    bundle["platt_calibrator"] = None
    bundle["platt_applied"] = result["platt_applied"]
    return bundle


def write_model_pickle(
    out_dir: Path,
    cat_model: M2Model,
    cat_result: dict[str, Any],
    inst_model: M2Model,
    inst_result: dict[str, Any],
    feature_cols: tuple[str, ...] = FEATURE_COLS,
) -> None:
    """Save the dual-model bundle as a pickle.

    Layout:
        {
          "approach": "dual_model",
          "catastrophic": {...},   # drives selective prediction
          "instability":  {...},   # drives cond1 AUROC
        }
    """
    bundle: dict[str, Any] = {
        "approach": "dual_model",
        "catastrophic": _model_to_bundle(cat_model, feature_cols, cat_result),
        "instability": _model_to_bundle(inst_model, feature_cols, inst_result),
    }
    with (out_dir / "m2_model.pkl").open("wb") as fh:
        pickle.dump(bundle, fh)


def write_run_metadata(
    out_dir: Path,
    train_rows: list[dict[str, Any]],
    val_rows: list[dict[str, Any]],
    train_labels: dict[str, np.ndarray],
    val_labels: dict[str, np.ndarray],
    cat_model: M2Model,
    cat_result: dict[str, Any],
    inst_model: M2Model,
    inst_result: dict[str, Any],
    summary: dict[str, Any],
    elapsed: float,
    smoke: bool,
) -> None:
    """Write run metadata JSON (dual-model approach)."""
    metadata = {
        "date": datetime.now().isoformat(timespec="seconds"),
        "script": "run_phaseT_wp3_m2_selective.py",
        "approach": "dual_model",
        "smoke": smoke,
        "runtime_seconds": round(elapsed, 3),
        "feature_cols": list(FEATURE_COLS),
        "n_train_episodes": len(train_rows),
        "n_val_episodes": len(val_rows),
        "n_train_queries": len({r["query_case_id"] for r in train_rows}),
        "n_val_queries": len({r["query_case_id"] for r in val_rows}),
        "label_thresholds": {
            "instability_gap": INSTABILITY_GAP_THRESHOLD,
            "catastrophic_dice": CATASTROPHIC_DICE_THRESHOLD,
            "tail_risk_quantile": TAIL_RISK_QUANTILE,
            "tail_risk_threshold": float(train_labels["tail_threshold"]),
        },
        "gate_thresholds": {
            "auroc": GATE_AUROC_THRESHOLD,
            "ece": GATE_ECE_THRESHOLD,
            "ece_calibrated": GATE_ECE_CALIBRATED_THRESHOLD,
            "cfr_reduction": GATE_CFR_REDUCTION_THRESHOLD,
            "coverage": GATE_COVERAGE,
        },
        "prevalence": {
            "train_instability": float(np.mean(train_labels["instability"])),
            "train_catastrophic": float(np.mean(train_labels["catastrophic"])),
            "train_tail_risk": float(np.mean(train_labels["tail_risk"])),
            "val_instability": float(np.mean(val_labels["instability"])),
            "val_catastrophic": float(np.mean(val_labels["catastrophic"])),
        },
        "catastrophic_model": {
            "name": cat_model.name,
            "metrics": {
                "auroc_instability": cat_result["auroc_instability"],
                "auprc_instability": cat_result["auprc_instability"],
                "auprc_catastrophic": cat_result["auprc_catastrophic"],
                "ece": cat_result["ece"],
                "ece_calibrated": cat_result["ece_calibrated"],
                "platt_applied": cat_result["platt_applied"],
                "cfr_reduction_at_80": cat_result["cfr_reduction_at_80"],
                "dice_change_at_80": cat_result["dice_change_at_80"],
            },
        },
        "instability_model": {
            "name": inst_model.name,
            "metrics": {
                "auroc_instability": inst_result["auroc_instability"],
                "auprc_instability": inst_result["auprc_instability"],
                "auprc_catastrophic": inst_result["auprc_catastrophic"],
                "ece": inst_result["ece"],
                "ece_calibrated": inst_result["ece_calibrated"],
                "platt_applied": inst_result["platt_applied"],
                "cfr_reduction_at_80": inst_result["cfr_reduction_at_80"],
                "dice_change_at_80": inst_result["dice_change_at_80"],
            },
        },
        "gate_decision": summary["decision"],
    }
    (out_dir / "run_metadata.json").write_text(
        json.dumps(metadata, indent=2), encoding="utf-8",
    )


