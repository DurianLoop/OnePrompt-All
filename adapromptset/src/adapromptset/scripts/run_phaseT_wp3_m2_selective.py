class M2Model:
    """Base class for M2 selective prediction models."""

    name: str
    model_type: str

    def fit(self, X: np.ndarray, y: np.ndarray) -> None:
        raise NotImplementedError

    def predict_risk(self, X: np.ndarray) -> np.ndarray:
        """Return risk scores in [0, 1] (probability of instability)."""
        raise NotImplementedError


class M2ThresholdModel(M2Model):
    """Single-feature threshold model (M2-0 entropy, M2-1 disagreement).

    The feature value is the risk score (min-max normalised to [0, 1]).
    A best threshold is found via Youden's J statistic for reporting.
    """

    def __init__(self, name: str, feature_index: int, feature_name: str):
        self.name = name
        self.model_type = "threshold"
        self.feature_index = feature_index
        self.feature_name = feature_name
        self.fmin = 0.0
        self.fmax = 1.0
        self.best_threshold = 0.5
        self.best_threshold_raw = 0.0

    def fit(self, X: np.ndarray, y: np.ndarray) -> None:
        feat = X[:, self.feature_index].astype(np.float64)
        self.fmin = float(feat.min()) if len(feat) else 0.0
        self.fmax = float(feat.max()) if len(feat) else 1.0
        if self.fmax <= self.fmin:
            self.fmax = self.fmin + 1.0
        # Sweep thresholds (min to max of the feature) to find best Youden's J.
        n_sweep = 200
        thresholds = np.linspace(self.fmin, self.fmax, n_sweep)
        best_j = -1.0
        for thr in thresholds:
            pred = (feat >= thr).astype(int)
            tp = float(np.sum((pred == 1) & (y == 1)))
            fp = float(np.sum((pred == 1) & (y == 0)))
            fn = float(np.sum((pred == 0) & (y == 1)))
            tn = float(np.sum((pred == 0) & (y == 0)))
            denom_pos = tp + fn
            denom_neg = fp + tn
            tpr = tp / denom_pos if denom_pos > 0 else 0.0
            fpr = fp / denom_neg if denom_neg > 0 else 0.0
            j = tpr - fpr
            if j > best_j:
                best_j = j
                self.best_threshold_raw = float(thr)
                if self.fmax > self.fmin:
                    self.best_threshold = float(
                        (thr - self.fmin) / (self.fmax - self.fmin)
                    )
                else:
                    self.best_threshold = 0.5

    def predict_risk(self, X: np.ndarray) -> np.ndarray:
        feat = X[:, self.feature_index].astype(np.float64)
        risk = (feat - self.fmin) / (self.fmax - self.fmin)
        return np.clip(risk, 0.0, 1.0)


class M2SklearnModel(M2Model):
    """Sklearn-based model (M2-2 logistic, M2-3 gradient boosting, M2-4 MLP)."""

    def __init__(self, name: str, estimator: Any):
        self.name = name
        self.model_type = "sklearn"
        self.estimator = estimator
        self.scaler = StandardScaler()

    def fit(self, X: np.ndarray, y: np.ndarray) -> None:
        Xs = self.scaler.fit_transform(X)
        self.estimator.fit(Xs, y)

    def predict_risk(self, X: np.ndarray) -> np.ndarray:
        Xs = self.scaler.transform(X)
        proba = self.estimator.predict_proba(Xs)
        return proba[:, 1]


def build_all_models() -> list[M2Model]:
    """Build the 5 M2 models (M2-0 .. M2-4)."""
    return [
        # M2-0: entropy threshold (matching_map_disagreement as entropy proxy)
        M2ThresholdModel("M2-0_entropy_threshold", 0, FEATURE_COLS[0]),
        # M2-1: disagreement threshold (matching_map_disagreement)
        M2ThresholdModel("M2-1_disagreement_threshold", 0, FEATURE_COLS[0]),
        # M2-2: logistic regression
        M2SklearnModel(
            "M2-2_logistic_regression",
            LogisticRegression(
                C=1.0, max_iter=1000, random_state=RANDOM_STATE, solver="lbfgs",
            ),
        ),
        # M2-3: gradient boosting
        M2SklearnModel(
            "M2-3_gradient_boosting",
            GradientBoostingClassifier(
                n_estimators=100, max_depth=3, random_state=RANDOM_STATE,
            ),
        ),
        # M2-4: small MLP
        M2SklearnModel(
            "M2-4_small_mlp",
            MLPClassifier(
                hidden_layer_sizes=(16, 8), max_iter=500,
                random_state=RANDOM_STATE, early_stopping=False,
            ),
        ),
    ]


