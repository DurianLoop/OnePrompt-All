def safe_auroc(y_true: np.ndarray, y_score: np.ndarray) -> float:
    """AUROC, returns 0.5 if undefined (single class)."""
    if len(np.unique(y_true)) < 2:
        return 0.5
    return float(roc_auc_score(y_true, y_score))


def safe_auprc(y_true: np.ndarray, y_score: np.ndarray) -> float:
    """AUPRC (average precision), returns prevalence if undefined."""
    if len(y_true) == 0:
        return 0.0
    if len(np.unique(y_true)) < 2:
        return float(np.mean(y_true))
    return float(average_precision_score(y_true, y_score))


def compute_ece(
    y_true: np.ndarray, y_prob: np.ndarray, n_bins: int = N_CALIBRATION_BINS,
) -> tuple[float, list[dict[str, Any]]]:
    """Expected Calibration Error with equal-width bins.

    Returns (ece, bin_data) where bin_data has per-bin lower/upper/count/
    accuracy/confidence/gap.
    """
    y_true = np.asarray(y_true, dtype=np.float64)
    y_prob = np.asarray(y_prob, dtype=np.float64)
    y_pred = (y_prob >= 0.5).astype(int)
    # Confidence in the predicted class.
    confidences = np.where(y_pred == 1, y_prob, 1.0 - y_prob)
    accuracies = (y_pred == y_true.astype(int)).astype(np.float64)
    n = len(y_true)
    if n == 0:
        return 0.0, []
    bin_edges = np.linspace(0.0, 1.0, n_bins + 1)
    ece = 0.0
    bin_data: list[dict[str, Any]] = []
    for i in range(n_bins):
        lo = bin_edges[i]
        hi = bin_edges[i + 1]
        if i == 0:
            mask = (confidences >= lo) & (confidences <= hi)
        else:
            mask = (confidences > lo) & (confidences <= hi)
        count = int(mask.sum())
        if count == 0:
            bin_acc = 0.0
            bin_conf = 0.0
        else:
            bin_acc = float(accuracies[mask].mean())
            bin_conf = float(confidences[mask].mean())
        gap = abs(bin_acc - bin_conf)
        ece += (count / n) * gap
        bin_data.append({
            "bin_index": i,
            "lower": round(lo, 4),
            "upper": round(hi, 4),
            "count": count,
            "accuracy": round(bin_acc, 6),
            "confidence": round(bin_conf, 6),
            "gap": round(gap, 6),
        })
    return float(ece), bin_data


# ---------------------------------------------------------------------------
# Platt scaling (calibration)
# ---------------------------------------------------------------------------

def fit_platt_scaler(
    train_probs: np.ndarray, train_labels: np.ndarray,
) -> LogisticRegression | None:
    """Fit Platt scaling (LogisticRegression on predicted probabilities)."""
    if len(np.unique(train_labels)) < 2:
        return None
    calibrator = LogisticRegression(
        C=1.0, solver="lbfgs", max_iter=1000, random_state=RANDOM_STATE,
    )
    calibrator.fit(train_probs.reshape(-1, 1), train_labels)
    return calibrator


def apply_platt_scaler(
    calibrator: LogisticRegression | None, probs: np.ndarray,
) -> np.ndarray:
    """Apply Platt scaling to predicted probabilities."""
    if calibrator is None:
        return probs
    return calibrator.predict_proba(probs.reshape(-1, 1))[:, 1]


# ---------------------------------------------------------------------------
# Risk-coverage curve
# ---------------------------------------------------------------------------

def compute_risk_coverage(
    risk_scores: np.ndarray,
    mean_dice: np.ndarray,
    catastrophic_labels: np.ndarray,
    coverages: np.ndarray | None = None,
) -> list[dict[str, Any]]:
    """Compute the risk-coverage curve.

    Sort episodes by predicted risk (descending). At coverage c, abstain on
    the top (1-c) fraction (highest risk) and evaluate on the remaining c
    fraction (lowest risk).
    """
    n = len(risk_scores)
    if n == 0:
        return []
    if coverages is None:
        coverages = np.arange(0.1, 1.01, 0.1)

    # Sort by risk descending (highest risk first).
    order = np.argsort(-risk_scores, kind="stable")
    sorted_dice = mean_dice[order]
    sorted_cat = catastrophic_labels[order]

    cfr_all = float(np.mean(catastrophic_labels)) if n else 0.0
    dice_all = float(np.mean(mean_dice)) if n else 0.0

    rows: list[dict[str, Any]] = []
    for cov in coverages:
        n_abstain = int(round((1.0 - cov) * n))
        n_covered = n - n_abstain
        if n_covered <= 0:
            n_covered = 1
        # Covered = the tail of the sorted array (lowest risk).
        covered_dice = sorted_dice[n_abstain:]
        covered_cat = sorted_cat[n_abstain:]
        if len(covered_dice) == 0:
            covered_dice = sorted_dice[-1:]
            covered_cat = sorted_cat[-1:]
        sel_dice = float(np.mean(covered_dice))
        sel_cfr = float(np.mean(covered_cat))
        abstention = 1.0 - (len(covered_dice) / n)
        cost = abstention + (1.0 - abstention) * sel_cfr
        rows.append({
            "coverage": round(float(cov), 4),
            "abstention_rate": round(abstention, 6),
            "selective_dice": round(sel_dice, 6),
            "selective_cfr": round(sel_cfr, 6),
            "cost": round(cost, 6),
            "n_covered": int(len(covered_dice)),
            "dice_all": round(dice_all, 6),
            "cfr_all": round(cfr_all, 6),
        })
    return rows


def metrics_at_coverage(
    risk_scores: np.ndarray,
    mean_dice: np.ndarray,
    catastrophic_labels: np.ndarray,
    coverage: float = GATE_COVERAGE,
) -> dict[str, float]:
    """Compute CFR / Dice metrics at a single coverage level."""
    n = len(risk_scores)
    if n == 0:
        return {"cfr": 0.0, "dice": 0.0, "cfr_all": 0.0, "dice_all": 0.0,
                "cfr_reduction": 0.0, "dice_change": 0.0}
    order = np.argsort(-risk_scores, kind="stable")
    sorted_dice = mean_dice[order]
    sorted_cat = catastrophic_labels[order]
    n_abstain = int(round((1.0 - coverage) * n))
    covered_dice = sorted_dice[n_abstain:]
    covered_cat = sorted_cat[n_abstain:]
    if len(covered_dice) == 0:
        covered_dice = sorted_dice[-1:]
        covered_cat = sorted_cat[-1:]
    cfr_all = float(np.mean(catastrophic_labels))
    dice_all = float(np.mean(mean_dice))
    cfr_cov = float(np.mean(covered_cat))
    dice_cov = float(np.mean(covered_dice))
    if cfr_all > 0:
        cfr_reduction = (cfr_all - cfr_cov) / cfr_all
    else:
        # No catastrophic failures to reduce; reduction undefined, treat as 0.
        cfr_reduction = 0.0
    dice_change = dice_cov - dice_all
    return {
        "cfr": cfr_cov,
        "dice": dice_cov,
        "cfr_all": cfr_all,
        "dice_all": dice_all,
        "cfr_reduction": cfr_reduction,
        "dice_change": dice_change,
    }


